-- Insert parents before children (a parent must exist first): one pass per depth.
do $$
declare
  lvl integer;
begin
  for lvl in 1..3 loop
    insert into public.framework_items
      (framework_id, parent_id, code, title, item_type, sort_order)
    select f.id, p.id, s.code, s.title, 'clause', s.n
    from _seed_items s
    join public.frameworks f on f.code = s.fw_code
    left join public.framework_items p
      on p.framework_id = f.id and p.code = s.parent_code
    where (length(s.code) - length(replace(s.code, '.', ''))) + 1 = lvl;
  end loop;
end
$$;

